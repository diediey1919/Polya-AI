#!/usr/bin/env python3
"""
Jalur 3 Manual Assistant: Fast Ingestion & Pipeline Runner for Zuma Transcripts.
Allows dropping or pasting transcripts copied from youtube-transcript.ai.
Automatically formats raw_transcript.txt, builds segmented_transcript.json,
updates metadata.json, and syncs into Polya Video Pipeline.
"""

import os
import re
import sys
import json
import time
import argparse
from pathlib import Path
from typing import List, Dict, Any, Tuple

CORPUS_BASE = Path("/home/ubuntu/skills/debate/zuma/corpus")
INCOMING_DIR = Path("/home/ubuntu/incoming_transcripts")
INCOMING_DIR.mkdir(parents=True, exist_ok=True)


def parse_timestamp_str(ts_str: str) -> float:
    """Parses MM:SS or HH:MM:SS string to seconds."""
    ts_str = ts_str.strip("[]()")
    parts = ts_str.split(":")
    if len(parts) == 2:
        return int(parts[0]) * 60 + float(parts[1])
    elif len(parts) == 3:
        return int(parts[0]) * 3600 + int(parts[1]) * 60 + float(parts[2])
    return 0.0


def format_seconds(seconds: float) -> str:
    total_seconds = int(seconds)
    hours, remainder = divmod(total_seconds, 3600)
    minutes, secs = divmod(remainder, 60)
    if hours > 0:
        return f"{hours}:{minutes:02d}:{secs:02d}"
    return f"{minutes}:{secs:02d}"


def parse_raw_pasted_text(text: str) -> List[Tuple[float, str]]:
    """
    Parses flexible transcript text copied from youtube-transcript.ai.
    Handles:
      [0:15] Text here
      0:15 Text here
      0:15\nText here
    """
    lines = text.splitlines()
    segments = []
    
    ts_pattern = re.compile(r'^(?:\[)?(\d{1,2}:\d{2}(?::\d{2})?)(?:\])?\s*(.*)$')
    
    current_ts = 0.0
    current_text = []

    for line in lines:
        stripped = line.strip()
        if not stripped:
            continue
        
        # Skip site headers/footers
        if "youtube-transcript.ai" in stripped.lower() or "interactive version" in stripped.lower():
            continue
        if stripped.startswith("# Transcript:") or stripped.startswith("Source video:"):
            continue
        if stripped == "## Transcript":
            continue

        match = ts_pattern.match(stripped)
        if match:
            # If we had a previous pending segment, save it
            if current_text:
                full_segment_text = " ".join(current_text).strip()
                if full_segment_text:
                    segments.append((current_ts, full_segment_text))
                current_text = []

            ts_str, remaining_text = match.groups()
            current_ts = parse_timestamp_str(ts_str)
            if remaining_text:
                current_text.append(remaining_text)
        else:
            current_text.append(stripped)

    if current_text:
        full_segment_text = " ".join(current_text).strip()
        if full_segment_text:
            segments.append((current_ts, full_segment_text))

    return segments


def ingest_transcript_to_corpus(video_dir: Path, raw_text: str) -> bool:
    meta_path = video_dir / "metadata.json"
    raw_txt_path = video_dir / "raw_transcript.txt"
    seg_json_path = video_dir / "segmented_transcript.json"

    if not meta_path.exists():
        print(f"Error: {meta_path} does not exist.")
        return False

    with open(meta_path, "r", encoding="utf-8") as f:
        meta = json.load(f)

    video_id = meta.get("youtube_id") or meta.get("video_id")
    title = meta.get("title", f"Video {video_id}")
    folder_id = video_dir.name

    parsed_segments = parse_raw_pasted_text(raw_text)
    if not parsed_segments:
        print(f"Warning: No valid timed segments could be parsed for {folder_id}.")
        return False

    # Build standardized segments and raw_lines
    segments_json_list = []
    formatted_raw_lines = [
        f"# Transcript: {title}\n",
        f"Source video: https://www.youtube.com/watch?v={video_id}",
        f"Language: id (timed text extraction) · Segments: {len(parsed_segments)}",
        f"Generated by https://youtube-transcript.ai — free YouTube transcript & summary extractor.\n",
        "## Transcript\n"
    ]

    total_words = 0
    for idx, (start_sec, seg_txt) in enumerate(parsed_segments, start=1):
        ts_str = format_seconds(start_sec)
        total_words += len(seg_txt.split())

        duration = 5.0
        if idx < len(parsed_segments):
            next_start = parsed_segments[idx][0]
            if next_start > start_sec:
                duration = min(next_start - start_sec, 60.0)

        segments_json_list.append({
            "segment_id": f"SEG-{video_id}-{idx:04d}",
            "video_id": meta.get("video_id", folder_id),
            "timestamp": ts_str,
            "start": start_sec,
            "duration": duration,
            "speaker": "SPEAKER",
            "text": seg_txt
        })

        formatted_raw_lines.append(f"[{ts_str}] {seg_txt}\n")

    full_raw_doc = "\n".join(formatted_raw_lines)

    # 1. Write raw_transcript.txt
    with open(raw_txt_path, "w", encoding="utf-8") as f:
        f.write(full_raw_doc)

    # 2. Write segmented_transcript.json
    segmented_data = {
        "video_id": meta.get("video_id", folder_id),
        "youtube_id": video_id,
        "title": title,
        "total_segments": len(segments_json_list),
        "total_words": total_words,
        "segments": segments_json_list
    }
    with open(seg_json_path, "w", encoding="utf-8") as f:
        json.dump(segmented_data, f, indent=2, ensure_ascii=False)

    # 3. Update metadata.json
    meta["transcript_source"] = "youtube-transcript.ai (timed text extraction)"
    meta["transcript_status"] = "OBTAINED"
    meta["raw_character_count"] = len(full_raw_doc)
    meta["raw_line_count"] = len(formatted_raw_lines)
    meta["total_segments"] = len(segments_json_list)
    meta["total_words"] = total_words
    meta["updated_at"] = time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())

    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2, ensure_ascii=False)

    print(f"[{folder_id}] SUCCESS: Ingested {len(segments_json_list)} segments ({len(full_raw_doc):,} bytes).")
    return True


def list_next_batch(count: int = 10):
    all_dirs = sorted(
        [d for d in CORPUS_BASE.iterdir() if d.is_dir() and d.name.startswith("video-")],
        key=lambda p: int(p.name.split("-")[1]) if p.name.split("-")[1].isdigit() else 999999
    )

    targets = []
    for d in all_dirs:
        raw_p = d / "raw_transcript.txt"
        if not raw_p.exists() or raw_p.stat().st_size <= 2000:
            targets.append(d)

    print(f"\n=======================================================")
    print(f"TOTAL SISA VIDEO BELUM LENGKAP: {len(targets)} VIDEO")
    print(f"MENAMPILKAN BATCH BERIKUTNYA ({min(count, len(targets))} VIDEO):")
    print(f"=======================================================\n")

    for idx, d in enumerate(targets[:count], start=1):
        with open(d / "metadata.json") as f:
            m = json.load(f)
        folder = d.name
        vid = m.get("youtube_id")
        title = m.get("title")
        print(f"[{idx}] {folder} | ID: {vid}")
        print(f"    Judul: {title}")
        print(f"    Link : https://youtube-transcript.ai/transcript?v={vid}\n")


def scan_incoming_folder():
    """Scans /home/ubuntu/incoming_transcripts/ for files like video-011.txt or g7mmqv4Y6XE.txt"""
    files = list(INCOMING_DIR.glob("*.txt"))
    if not files:
        print(f"Tidak ada file .txt ditemukan di {INCOMING_DIR}")
        print(f"Letakkan file seperti 'video-011.txt' atau 'g7mmqv4Y6XE.txt' di direktori tersebut.")
        return

    print(f"Menemukan {len(files)} file di {INCOMING_DIR}. Memproses...")

    for fpath in files:
        stem = fpath.stem.strip() # e.g. video-011 or g7mmqv4Y6XE
        target_dir = None

        if (CORPUS_BASE / stem).is_dir():
            target_dir = CORPUS_BASE / stem
        else:
            # Match by youtube_id
            for d in CORPUS_BASE.iterdir():
                m_path = d / "metadata.json"
                if m_path.exists():
                    try:
                        with open(m_path) as mf:
                            m = json.load(mf)
                        if m.get("youtube_id") == stem:
                            target_dir = d
                            break
                    except Exception:
                        pass

        if not target_dir:
            print(f"Lewati {fpath.name}: Tidak cocok dengan folder video atau ID YouTube mana pun.")
            continue

        with open(fpath, "r", encoding="utf-8") as f:
            content = f.read()

        ok = ingest_transcript_to_corpus(target_dir, content)
        if ok:
            # Move processed file to archive
            done_dir = INCOMING_DIR / "done"
            done_dir.mkdir(exist_ok=True)
            fpath.rename(done_dir / fpath.name)


def main():
    parser = argparse.ArgumentParser(description="Jalur 3 Manual Assistant for Polya Zuma Transcripts")
    parser.add_argument("--batch", type=int, default=0, help="Tampilkan N daftar link YouTube Transcript berikutnya")
    parser.add_argument("--scan", action="store_true", help="Scan & ingest seluruh file di /home/ubuntu/incoming_transcripts/")
    parser.add_argument("--ingest-file", type=str, help="Path file teks yang ingin di-ingest")
    parser.add_argument("--target", type=str, help="Target folder atau video_id (misal: video-011 atau g7mmqv4Y6XE)")

    args = parser.parse_args()

    if args.batch > 0:
        list_next_batch(args.batch)
        return

    if args.scan:
        scan_incoming_folder()
        return

    if args.ingest_file and args.target:
        t_path = Path(args.ingest_file)
        if not t_path.exists():
            print(f"File {t_path} tidak ditemukan.")
            sys.exit(1)

        target_dir = CORPUS_BASE / args.target
        if not target_dir.exists():
            # Search by ID
            for d in CORPUS_BASE.iterdir():
                m_path = d / "metadata.json"
                if m_path.exists():
                    try:
                        with open(m_path) as mf:
                            m = json.load(mf)
                        if m.get("youtube_id") == args.target:
                            target_dir = d
                            break
                    except Exception:
                        pass

        if not target_dir or not target_dir.exists():
            print(f"Target {args.target} tidak ditemukan di corpus.")
            sys.exit(1)

        with open(t_path, "r", encoding="utf-8") as f:
            content = f.read()

        ingest_transcript_to_corpus(target_dir, content)
        return

    # Default action if no args
    list_next_batch(10)


if __name__ == "__main__":
    main()
